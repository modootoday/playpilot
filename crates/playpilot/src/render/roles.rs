//! `playpilot render roles`: the plugin's agent definitions as project files.
//!
//! Cloud sessions do not load Claude Code plugins, so the agents a `Role`
//! names (`agent = "playpilot:<name>"`) are written into the checkout as
//! `.claude/agents/playpilot-<name>.md`. The texts are built into the binary.

use std::collections::BTreeSet;

use crate::validate::{self, Resource};

/// The plugin's agent definitions, by name.
pub const PLUGIN_AGENTS: &[(&str, &str)] = &[
    (
        "heavy-builder",
        include_str!("../../../../plugin/agents/heavy-builder.md"),
    ),
    (
        "implementer",
        include_str!("../../../../plugin/agents/implementer.md"),
    ),
    (
        "reviewer",
        include_str!("../../../../plugin/agents/reviewer.md"),
    ),
    (
        "windows-validator",
        include_str!("../../../../plugin/agents/windows-validator.md"),
    ),
];

const AGENT_PREFIX: &str = "playpilot:";
pub const GENERATED: &str = "# generated by playpilot render roles; edit the fleet config instead";

/// A lower-case name of letters, digits and single inner hyphens.
pub fn is_role_name(n: &str) -> bool {
    !n.is_empty()
        && n.starts_with(|c: char| c.is_ascii_lowercase())
        && !n.ends_with('-')
        && !n.contains("--")
        && n.bytes()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'-')
}

fn plugin_agent(name: &str) -> Option<&'static str> {
    PLUGIN_AGENTS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, t)| *t)
}

/// The plugin agent a role names, `None` when it names no playpilot agent.
fn role_agent(role: &Resource) -> Result<Option<String>, String> {
    let Some(agent) = validate::string(&role.spec, "agent") else {
        return Ok(None);
    };
    let Some(name) = agent.strip_prefix(AGENT_PREFIX) else {
        return Ok(None);
    };
    if !is_role_name(name) {
        return Err(format!(
            "{}: agent \"{agent}\" is not a plain lower-case-hyphen name",
            role.file
        ));
    }
    if plugin_agent(name).is_none() {
        return Err(format!(
            "{}: agent \"{agent}\" is not a playpilot plugin agent",
            role.file
        ));
    }
    Ok(Some(name.to_string()))
}

/// The plugin agents `project` uses: those of the roles its sessions name,
/// or, when it has no session, every role that names a plugin agent.
pub fn project_agents(resources: &[Resource], project: &str) -> Result<Vec<String>, String> {
    super::find(resources, "Project", project)?;
    let roles: BTreeSet<String> = resources
        .iter()
        .filter(|r| {
            r.kind == "Session" && validate::string(&r.spec, "project").as_deref() == Some(project)
        })
        .filter_map(|s| validate::string(&s.spec, "role"))
        .collect();
    let mut agents = BTreeSet::new();
    if roles.is_empty() {
        for r in resources.iter().filter(|r| r.kind == "Role") {
            if let Ok(Some(a)) = role_agent(r) {
                agents.insert(a);
            }
        }
    } else {
        for role in &roles {
            if let Some(a) = role_agent(super::find(resources, "Role", role)?)? {
                agents.insert(a);
            }
        }
    }
    Ok(agents.into_iter().collect())
}

/// The file text: the plugin definition with the generated marker as the
/// first body line, LF line endings whatever the checkout used.
pub fn role_file(name: &str) -> Result<String, String> {
    if !is_role_name(name) {
        return Err(format!("\"{name}\" is not a plain lower-case-hyphen name"));
    }
    let source = plugin_agent(name)
        .ok_or_else(|| format!("\"{name}\" is not a playpilot plugin agent"))?
        .replace("\r\n", "\n");
    let body = source
        .strip_prefix("---\n")
        .and_then(|rest| rest.find("\n---\n").map(|i| 4 + i + 5))
        .ok_or_else(|| format!("plugin/agents/{name}.md: no frontmatter"))?;
    let (front, rest) = source.split_at(body);
    // Namespace the agent so it cannot collide with a project's own agent.
    let plain = format!("\nname: {name}\n");
    if !front.contains(&plain) {
        return Err(format!(
            "plugin/agents/{name}.md: frontmatter has no `name: {name}`"
        ));
    }
    let front = front.replacen(&plain, &format!("\nname: playpilot-{name}\n"), 1);
    Ok(format!("{front}{GENERATED}\n{rest}"))
}

/// The file name a plugin agent is written under in `.claude/agents/`.
pub fn file_name(name: &str) -> String {
    format!("playpilot-{name}.md")
}
